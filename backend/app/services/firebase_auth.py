"""Firebase Admin SDK Authentication and Token Verification Service.

Verifies Firebase ID tokens generated by client-side Firebase Auth
(Google OAuth, Phone OTP, Email/Password) and resolves user claims.
"""

import logging
from pathlib import Path
from typing import Any, Callable, Dict, Optional

import firebase_admin
from firebase_admin import auth, credentials
from fastapi import HTTPException, status

from app.core.config import settings

logger = logging.getLogger("campusway.firebase_auth")

_mock_firebase_verifier: Optional[Callable[[str], Dict[str, Any]]] = None
_firebase_initialized = False


def _resolve_service_account_path() -> Optional[Path]:
    """Find the Firebase service account credentials file in common locations."""
    candidates = [
        Path(settings.FIREBASE_SERVICE_ACCOUNT_PATH),
        Path("backend") / settings.FIREBASE_SERVICE_ACCOUNT_PATH,
        Path("backend/secrets/campusway-firebase-admin.json"),
        Path("secrets/campusway-firebase-admin.json"),
        Path("backend/secrets/campusway-firebase-admin.json.json"),
        Path("secrets/campusway-firebase-admin.json.json"),
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate.resolve()
    return None


def get_firebase_admin_app() -> Optional[firebase_admin.App]:
    """Initialize or retrieve the Firebase Admin SDK application singleton."""
    global _firebase_initialized
    if _firebase_initialized or firebase_admin._apps:
        _firebase_initialized = True
        return firebase_admin.get_app()

    sa_path = _resolve_service_account_path()
    if not sa_path:
        logger.warning(
            "Firebase Admin service account credential file not found. "
            "Firebase token verification will fail unless mocked."
        )
        return None

    try:
        cred = credentials.Certificate(str(sa_path))
        app = firebase_admin.initialize_app(cred, {
            "projectId": settings.FIREBASE_PROJECT_ID,
        })
        _firebase_initialized = True
        logger.info(f"Firebase Admin SDK initialized successfully for project {settings.FIREBASE_PROJECT_ID}.")
        return app
    except Exception as e:
        logger.error(f"Failed to initialize Firebase Admin SDK: {e}")
        return None


def is_firebase_configured() -> bool:
    """Check whether Firebase Admin credentials are available."""
    if _mock_firebase_verifier:
        return True
    return bool(_resolve_service_account_path())


def set_mock_firebase_verifier(fn: Optional[Callable[[str], Dict[str, Any]]]) -> None:
    """Set a mock verifier callback for automated test suites."""
    global _mock_firebase_verifier
    _mock_firebase_verifier = fn


def verify_firebase_id_token(id_token: str) -> Dict[str, Any]:
    """Verify a Firebase ID token and return normalized claims.

    Claims dict contains:
    - uid: Firebase UID (stable user identifier)
    - email: Optional email address
    - email_verified: Boolean
    - name: Optional display name
    - phone_number: Optional E.164 phone number
    - picture: Optional avatar URL
    - sign_in_provider: e.g. 'google.com', 'phone', 'password'
    """
    if _mock_firebase_verifier:
        return _mock_firebase_verifier(id_token)

    app = get_firebase_admin_app()
    if not app:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "Firebase Authentication is not configured on the backend server. "
                "Ensure service account credentials exist in backend/secrets/campusway-firebase-admin.json."
            ),
        )

    try:
        decoded = auth.verify_id_token(id_token.strip(), app=app)
    except auth.ExpiredIdTokenError:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Firebase ID token has expired. Please sign in again.",
        )
    except auth.InvalidIdTokenError as e:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Invalid Firebase ID token: {str(e)}",
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Firebase token verification failed: {str(e)}",
        )

    firebase_meta = decoded.get("firebase", {})
    sign_in_provider = firebase_meta.get("sign_in_provider", "firebase")

    return {
        "uid": decoded.get("uid"),
        "email": decoded.get("email"),
        "email_verified": decoded.get("email_verified", False),
        "name": decoded.get("name"),
        "phone_number": decoded.get("phone_number"),
        "picture": decoded.get("picture"),
        "sign_in_provider": sign_in_provider,
    }
